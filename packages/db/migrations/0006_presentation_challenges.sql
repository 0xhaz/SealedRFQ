-- Challenges for Concordium identity presentations.
--
-- Separate from `wallet_challenges`, which proves control of an Arc address. This proves something
-- about a Concordium identity, and the two must not be interchangeable: a nonce issued to prove
-- "you hold this wallet" must never be spendable as "you are a qualified supplier".
--
-- The table follows the same shape as `0003_auth.sql` for the same reason. A challenge is issued
-- before there is anything to attribute it to, so it cannot be tenant-scoped, and the single-use
-- rule has to be enforced where two concurrent requests cannot both win. RLS is enabled with no
-- policy and the table is revoked from the application role, so the SECURITY DEFINER functions
-- below are the only way in and the escalation stays named and greppable.
--
-- In-memory would have been simpler and wrong: on a serverless deployment each invocation has its
-- own memory, so a challenge issued by one request would be unknown to the next. The failure would
-- look like intermittent "unknown challenge" errors rather than like a missing database.

CREATE TABLE presentation_challenges (
  challenge   text PRIMARY KEY,
  -- What it was issued for, e.g. `tender:42:bid`. Checked on verification, so a proof obtained
  -- for one purpose cannot be presented for another.
  purpose     text        NOT NULL CHECK (length(purpose) BETWEEN 1 AND 200),
  issued_at   timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL,
  consumed_at timestamptz,
  CHECK (expires_at > issued_at)
);

-- Expiry sweeps scan by time, not by key.
CREATE INDEX presentation_challenges_expiry ON presentation_challenges (expires_at)
  WHERE consumed_at IS NULL;

ALTER TABLE presentation_challenges ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON presentation_challenges FROM sealedrfq_app;

-- The challenge is generated by the caller, not here: it has to be cryptographically random, and
-- that is the application's business. This records it.
CREATE OR REPLACE FUNCTION app.issue_presentation_challenge(
  p_challenge text, p_purpose text, p_ttl interval
) RETURNS TABLE (challenge text, purpose text, issued_at timestamptz, expires_at timestamptz)
  LANGUAGE sql VOLATILE SECURITY DEFINER AS
$$
  INSERT INTO presentation_challenges (challenge, purpose, expires_at)
  VALUES (p_challenge, p_purpose, now() + p_ttl)
  RETURNING presentation_challenges.challenge, presentation_challenges.purpose,
            presentation_challenges.issued_at, presentation_challenges.expires_at
$$;

-- Look without spending. A proof that turns out to be invalid must not cost the holder the
-- challenge they were legitimately issued, or anyone able to post garbage could deny them it.
CREATE OR REPLACE FUNCTION app.peek_presentation_challenge(p_challenge text)
  RETURNS TABLE (challenge text, purpose text, issued_at timestamptz, expires_at timestamptz,
                 consumed_at timestamptz)
  LANGUAGE sql STABLE SECURITY DEFINER AS
$$
  SELECT presentation_challenges.challenge, presentation_challenges.purpose,
         presentation_challenges.issued_at, presentation_challenges.expires_at,
         presentation_challenges.consumed_at
    FROM presentation_challenges
   WHERE presentation_challenges.challenge = p_challenge
$$;

-- Spend it, once. Both conditions sit in the WHERE clause so there is no window between checking
-- and claiming: two presentations racing the same challenge cannot both be accepted. `now()` is
-- the database's, which is also why there is no clock to disagree about between the two calls.
CREATE OR REPLACE FUNCTION app.consume_presentation_challenge(p_challenge text)
  RETURNS TABLE (challenge text, purpose text, issued_at timestamptz, expires_at timestamptz)
  LANGUAGE sql VOLATILE SECURITY DEFINER AS
$$
  UPDATE presentation_challenges SET consumed_at = now()
   WHERE presentation_challenges.challenge = p_challenge
     AND presentation_challenges.consumed_at IS NULL
     AND presentation_challenges.expires_at > now()
  RETURNING presentation_challenges.challenge, presentation_challenges.purpose,
            presentation_challenges.issued_at, presentation_challenges.expires_at
$$;

-- Housekeeping only. An expired challenge is refused with or without this.
CREATE OR REPLACE FUNCTION app.evict_expired_presentation_challenges()
  RETURNS bigint LANGUAGE plpgsql VOLATILE SECURITY DEFINER AS
$$
DECLARE removed bigint;
BEGIN
  DELETE FROM presentation_challenges WHERE expires_at <= now() - interval '1 day';
  GET DIAGNOSTICS removed = ROW_COUNT;
  RETURN removed;
END;
$$;

GRANT EXECUTE ON FUNCTION app.issue_presentation_challenge(text, text, interval) TO sealedrfq_app;
GRANT EXECUTE ON FUNCTION app.peek_presentation_challenge(text) TO sealedrfq_app;
GRANT EXECUTE ON FUNCTION app.consume_presentation_challenge(text) TO sealedrfq_app;
GRANT EXECUTE ON FUNCTION app.evict_expired_presentation_challenges() TO sealedrfq_app;
